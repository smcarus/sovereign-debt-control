// 30-day historical time-series for CDS spreads
export function generateCDSTimeSeries(baseBps: number): { date: string; spread: number }[] {
  const result: { date: string; spread: number }[] = [];
  const now = new Date('2026-10-09');
  
  for (let i = 29; i >= 0; i--) {
    const d = new Date(now.getTime() - i * 24 * 60 * 60 * 1000);
    const dateStr = d.toISOString().split('T')[0];
    const noise = Math.sin(i * 0.4) * (baseBps * 0.05) + (Math.cos(i * 0.8) * (baseBps * 0.03));
    const spread = Math.max(10, Math.round(baseBps + noise));
    result.push({ date: dateStr, spread });
  }
  return result;
}
